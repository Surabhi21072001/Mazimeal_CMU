#!/usr/bin/env python3
"""
Provenance rows for ingredients: which USDA record each one was matched to.

    python3 scripts/ingredient_sources.py --review schema/seed/usda_matches.csv -o schema/seed/ingredient_sources.sql

Reads the review file scripts/match_usda.py writes and emits
ingredient_source_map rows (ingredient -> FDC id, description, score, how it
was matched). Rows under the score cutoff (ok = False) are left out, same as
their nutrition. Idempotent.
"""
import argparse, csv


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--review", default="schema/seed/usda_matches.csv")
    p.add_argument("--source", default="usda_sr_legacy")
    p.add_argument("-o", "--out", default="schema/seed/ingredient_sources.sql")
    a = p.parse_args()

    rows = [r for r in csv.DictReader(open(a.review, encoding="utf-8")) if r["ok"] == "True"]
    with open(a.out, "w", encoding="utf-8") as f:
        w = f.write
        w("-- Generated by scripts/ingredient_sources.py. Safe to run more than once.\nBEGIN;\n\n")
        for r in rows:
            how = "alias" if r["aliased"] == "True" else "fuzzy"
            w(f"INSERT INTO ingredient_source_map (ingredient_id, source_id, source_record_id, source_description, match_score, matched_by) "
              f"SELECT ingredient_id, {q(a.source)}, {q(r['fdc_id'])}, {q(r['description'])}, {int(r['score'])}, {q(how)} FROM ingredients "
              f"WHERE lower(btrim(ingredient_name)) = {q(r['name'].lower().strip())} "
              f"ON CONFLICT (ingredient_id, source_id) DO UPDATE SET source_record_id = EXCLUDED.source_record_id, "
              f"source_description = EXCLUDED.source_description, match_score = EXCLUDED.match_score, matched_by = EXCLUDED.matched_by;\n")
        w("\nCOMMIT;\n")
    print(f"{len(rows)} ingredients -> {a.out}")


if __name__ == "__main__":
    main()
