#!/usr/bin/env python3
"""
Turn recipe CSVs into a SQL file you can load with psql.

    python3 scripts/csv_to_sql.py schema/seed/recipes.csv schema/seed/recipe_ingredients.csv \
        -o schema/seed/batch1.sql
    psql -d mazimeal -v ON_ERROR_STOP=1 -f schema/seed/batch1.sql

Validates every row first and refuses to write SQL if anything's wrong, so a
bad CSV never gets halfway into the database. The SQL it writes is idempotent:
running it twice doesn't duplicate anything.

recipes.csv columns
    recipe_name*  meal_category*  dietary_tags  prep_time_min  cook_time_min
    difficulty_level  servings  calories_per_serving  regional_origin
    description  steps
    (* required; dietary_tags and steps are pipe-separated)

recipe_ingredients.csv columns
    recipe_name*  ingredient_name*  quantity*  unit*  preparation_note
    is_optional  food_category
"""
import argparse, csv, sys
from collections import Counter
from pathlib import Path

MEALS = {"Breakfast", "Lunch", "Dinner", "Snack"}
DIFF  = {"Easy", "Medium", "Hard", ""}


def q(v):
    """SQL string literal, or NULL for empty."""
    if v is None or str(v).strip() == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def num(v, field, row, errs, kind=int):
    if str(v).strip() == "":
        return None
    try:
        return kind(v)
    except ValueError:
        errs.append(f"{row}: {field} is not a number: {v!r}")
        return None


def load(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def validate(recipes, lines):
    errs = []
    names = Counter(r["recipe_name"].strip().lower() for r in recipes)
    for n, c in names.items():
        if c > 1:
            errs.append(f"recipes.csv: '{n}' appears {c} times")

    for i, r in enumerate(recipes, 2):
        tag = f"recipes.csv row {i}"
        if not r.get("recipe_name", "").strip():
            errs.append(f"{tag}: recipe_name is empty")
        if r.get("meal_category") not in MEALS:
            errs.append(f"{tag}: meal_category must be one of {sorted(MEALS)}, got {r.get('meal_category')!r}")
        if r.get("difficulty_level", "") not in DIFF:
            errs.append(f"{tag}: difficulty_level must be Easy/Medium/Hard or blank")
        for f in ("prep_time_min", "cook_time_min", "servings"):
            v = num(r.get(f, ""), f, tag, errs)
            if v is not None and v < 0:
                errs.append(f"{tag}: {f} is negative")
        num(r.get("calories_per_serving", ""), "calories_per_serving", tag, errs, float)

    known = set(names)
    seen_pairs = Counter()
    for i, l in enumerate(lines, 2):
        tag = f"recipe_ingredients.csv row {i}"
        rn = l.get("recipe_name", "").strip().lower()
        if not rn:
            errs.append(f"{tag}: recipe_name is empty")
        elif rn not in known:
            errs.append(f"{tag}: recipe '{l['recipe_name']}' is not in recipes.csv")
        if not l.get("ingredient_name", "").strip():
            errs.append(f"{tag}: ingredient_name is empty")
        qty = num(l.get("quantity", ""), "quantity", tag, errs, float)
        if qty is None or qty <= 0:
            errs.append(f"{tag}: quantity must be > 0")
        if not l.get("unit", "").strip():
            errs.append(f"{tag}: unit is empty")
        if l.get("is_optional", "false").lower() not in ("true", "false", ""):
            errs.append(f"{tag}: is_optional must be true or false")
        pair = (rn, l.get("ingredient_name", "").strip().lower())
        seen_pairs[pair] += 1
        if seen_pairs[pair] == 2:
            errs.append(f"{tag}: '{pair[1]}' listed twice for '{l['recipe_name']}'")

    no_lines = known - {l["recipe_name"].strip().lower() for l in lines}
    warns = [f"no ingredient lines for: {n}" for n in sorted(no_lines)]
    return errs, warns


def emit(recipes, lines, out):
    w = out.write
    w("-- Generated by scripts/csv_to_sql.py. Safe to run more than once.\n")
    w("BEGIN;\n\n")

    w("-- ingredients (skips any that already exist, case-insensitive)\n")
    seen = set()
    for l in lines:
        key = l["ingredient_name"].strip().lower()
        if key in seen: continue
        seen.add(key)
        cat = l.get("food_category", "").strip() or "Uncategorized"
        w(f"INSERT INTO ingredients (ingredient_name, food_category, data_source)\n"
          f"VALUES ({q(l['ingredient_name'].strip())}, {q(cat)}, 'Manual')\n"
          f"ON CONFLICT (lower(btrim(ingredient_name))) DO NOTHING;\n")

    w("\n-- recipes\n")
    for r in recipes:
        tags = [t.strip() for t in r.get("dietary_tags", "").split("|") if t.strip()]
        tags_sql = "ARRAY[" + ",".join(q(t) for t in tags) + "]::text[]" if tags else "NULL"
        steps = [s.strip() for s in r.get("steps", "").split("|") if s.strip()]
        desc = r.get("description", "").strip()
        if steps:
            desc = (desc + "\n\n" if desc else "") + "\n".join(f"{i}. {s}" for i, s in enumerate(steps, 1))
        w(f"INSERT INTO recipes (recipe_name, meal_category, dietary_tags, prep_time_min, cook_time_min,\n"
          f"    difficulty_level, servings, calories_per_serving, regional_origin, recipe_description, data_source)\n"
          f"VALUES ({q(r['recipe_name'].strip())}, {q(r['meal_category'])}, {tags_sql}, "
          f"{r.get('prep_time_min') or 'NULL'}, {r.get('cook_time_min') or 'NULL'},\n"
          f"    {q(r.get('difficulty_level'))}, {r.get('servings') or 4}, {r.get('calories_per_serving') or 'NULL'}, "
          f"{q(r.get('regional_origin'))}, {q(desc)}, 'Manual')\n"
          f"ON CONFLICT (lower(recipe_name)) WHERE deleted_at IS NULL DO NOTHING;\n")

    w("\n-- recipe_ingredients (resolved by name)\n")
    for l in lines:
        opt = "true" if l.get("is_optional", "").lower() == "true" else "false"
        w(f"INSERT INTO recipe_ingredients (recipe_id, ingredient_id, quantity, unit, preparation_note, is_optional)\n"
          f"SELECT r.recipe_id, i.ingredient_id, {float(l['quantity'])}, {q(l['unit'].strip())}, "
          f"{q(l.get('preparation_note'))}, {opt}\n"
          f"FROM recipes r, ingredients i\n"
          f"WHERE lower(r.recipe_name) = lower({q(l['recipe_name'].strip())}) AND r.deleted_at IS NULL\n"
          f"  AND lower(btrim(i.ingredient_name)) = lower({q(l['ingredient_name'].strip())})\n"
          f"ON CONFLICT (recipe_id, ingredient_id) DO NOTHING;\n")

    w("\nCOMMIT;\n")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("recipes_csv")
    p.add_argument("ingredients_csv")
    p.add_argument("-o", "--out", required=True)
    a = p.parse_args()

    recipes, lines = load(a.recipes_csv), load(a.ingredients_csv)
    errs, warns = validate(recipes, lines)
    for wn in warns: print("warning:", wn)
    if errs:
        for e in errs: print("error:", e)
        print(f"\n{len(errs)} error(s). Nothing written.")
        sys.exit(1)

    with open(a.out, "w", encoding="utf-8") as f:
        emit(recipes, lines, f)
    print(f"{len(recipes)} recipes, {len(lines)} ingredient lines -> {a.out}")


if __name__ == "__main__":
    main()
