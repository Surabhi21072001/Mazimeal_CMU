"""Build docs/run-log.md: for every saved run, what each stage selected, dropped and why.

Run from the project root: python -m scripts.build_run_log
Reads the JSON files in outputs/ listed in RUNS. A missing file is skipped.
Judgments about the runs (what was right or wrong) are in docs/run-notes.md, written by hand.
"""
import json
from pathlib import Path

from nutrition_fact_repository import NutritionFactRepository

OUTPUT_DIRECTORY = Path(__file__).resolve().parent.parent / "outputs"
LOG_PATH = Path(__file__).resolve().parent.parent / "docs" / "run-log.md"

# (title, file, kind): kind "bio" = bio stage only, "chef" = Chef only, "pipeline" = bio, synergy and Chef
RUNS = [
    ("Bio stage, seed 100, three-outcome prompt (20 recipes)", "bio_stage_seed_100.json", "bio"),
    ("Bio stage, seed 2373, three-outcome prompt (3 recipes)", "bio_stage_seed_2373.json", "bio"),
    ("Chef stage, seed 2373 (3 recipes, from the bio run above)", "chef_stage_seed_2373.json", "chef"),
    ("Pipeline, seed 7, BEFORE the synergy prompt rewrite", "pipeline_run_seed_7_before_synergy_prompt.json", "pipeline"),
    ("Pipeline, seed 7, AFTER the synergy prompt rewrite", "pipeline_run_seed_7.json", "pipeline"),
    ("Pipeline, Asian Baked Tofu, before the retry, prompt and marker fixes", "pipeline_run_named_tofu_before_fixes.json", "pipeline"),
    ("Pipeline, Gallo Pinto, after the retry and prompt fixes, before the list-marker fix", "pipeline_run_named_gallo_before_marker_fix.json", "pipeline"),
    ("Pipeline, Gallo Pinto, after all fixes", "pipeline_run_named_gallo_after_fixes.json", "pipeline"),
    ("Pipeline, Fish Tacos, Koshari, Souvlaki, after all fixes", "pipeline_run_seed_named.json", "pipeline"),
]


def total_tokens(tokens) -> str:
    if isinstance(tokens, dict) and tokens:
        return str(list(tokens.values())[0].get("total_tokens", "?"))
    return str(tokens) if tokens else "0 (cached)"


def stage_lines(stage_title: str, report: dict, triggers: dict, names: dict) -> list[str]:
    def label(rule_id):
        return f"{rule_id} ({names.get(rule_id, '?')})"

    lines = [f"**{stage_title}** (attempts: {report['attempts']})"]
    for rule_id in report["accepted_rule_ids"]:
        trigger_text = f", triggers {triggers[rule_id]}" if rule_id in triggers else ""
        lines.append(f"- SELECTED {label(rule_id)}{trigger_text}")
    for rule_id, quote in report.get("already_applied_quotes", {}).items():
        lines.append(f'- ALREADY APPLIED {label(rule_id)}: "{quote}"')
    for rule_id, reason in report["skipped_reasons"].items():
        lines.append(f"- DROPPED {label(rule_id)}: {reason}")
    if report["errors"]:
        lines.append(f"- governance errors seen ({len(report['errors'])}):")
        lines += [f"  - {error[:300]}" for error in report["errors"]]
    if report["attempts"] >= 3 and not report["accepted_rule_ids"] and report["errors"]:
        lines.append("- NOTE: three attempts used and errors seen; this stage may have been dropped as a failure")
    return lines


def chef_lines(report: dict, result: dict, names: dict) -> list[str]:
    lines = [f"**Chef** (attempts: {report['attempts']}, shipped: "
             f"{'ENHANCED' if result['change_log'] else 'ORIGINAL UNCHANGED'})"]
    for rule_id in report["accepted_rule_ids"]:
        lines.append(f"- APPLIED {rule_id} ({names.get(rule_id, '?')})")
    for rule_id, reason in report["skipped_reasons"].items():
        lines.append(f"- DECLINED {rule_id} ({names.get(rule_id, '?')}): {reason}")
    for change in result["change_log"]:
        lines.append(f"- change {change['rule_ids']}: `{change['text_before'][:90]}` -> `{change['text_after'][:200]}`")
    lines += [f"- suggestion (not applied): {note}" for note in result["adaptation_notes"]]
    if report["errors"]:
        lines.append(f"- governance errors seen ({len(report['errors'])}):")
        lines += [f"  - {error[:220]}" for error in report["errors"]]
    return lines


def main() -> None:
    repository = NutritionFactRepository()
    names = {**repository.fetch_rule_names("bioavailability"), **repository.fetch_rule_names("synergy")}
    out = ["# Run log", "",
           "Generated by `python -m scripts.build_run_log` from the saved runs in `outputs/`.",
           "Per recipe and stage: what was selected, already applied, or dropped, and the reason the model gave.",
           "Judgments about whether those calls were right are in `run-notes.md`.", ""]
    for title, file_name, kind in RUNS:
        path = OUTPUT_DIRECTORY / file_name
        if not path.exists():
            continue
        out += [f"## {title}", f"`outputs/{file_name}`", ""]
        for run in json.loads(path.read_text()):
            tokens = total_tokens(run.get("tokens"))
            if kind == "bio":
                recipe_title = run["recipe"]["title"]
                triggers = {fact["rule_id"]: fact["trigger_ingredients"] for fact in run["applicable_facts"]}
                body = stage_lines("Bioavailability", run["report"], triggers, names)
            elif kind == "chef":
                recipe_title = run["original"]["title"]
                body = chef_lines(run["result"]["stage_reports"][0], run["result"], names)
            else:
                recipe_title = run["original"]["title"]
                reports = run["result"]["stage_reports"]
                body = (stage_lines("Bioavailability", reports[0], {}, names) + [""]
                        + stage_lines("Synergy", reports[1], {}, names) + [""]
                        + chef_lines(reports[2], run["result"], names))
            out += [f"### {recipe_title}", f"tokens (new calls only, cached calls count 0): {tokens}", ""] + body + [""]
    LOG_PATH.write_text("\n".join(out))
    print(f"wrote {LOG_PATH} ({len(out)} lines)")


if __name__ == "__main__":
    main()
